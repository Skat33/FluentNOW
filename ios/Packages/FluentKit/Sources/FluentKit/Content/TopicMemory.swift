import Foundation

/// A remembered search query → topic (and optionally category) mapping. Queries answered by a
/// topic (built-in or generated) are stored so the next search for the same words is instant,
/// offline and unambiguous.
public struct TopicQueryAlias: Codable, Sendable, Hashable {
    /// `TopicSearch.queryKey` of the query.
    public var query: String
    public var topicID: String
    public var categoryID: String?
    public var updatedAt: Timestamp
    public var hits: Int

    public init(query: String, topicID: String, categoryID: String? = nil, updatedAt: Timestamp, hits: Int = 1) {
        self.query = query
        self.topicID = topicID
        self.categoryID = categoryID
        self.updatedAt = updatedAt
        self.hits = hits
    }

    enum CodingKeys: String, CodingKey {
        case query, topicID, categoryID, updatedAt, hits
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        query = try c.decode(String.self, forKey: .query)
        topicID = try c.decode(String.self, forKey: .topicID)
        categoryID = c.lenientOptionalString(.categoryID)
        updatedAt = c.lenientDouble(.updatedAt)
        hits = c.lenientInt(.hits, default: 1)
    }
}

/// All remembered queries (file `aliases.json` of the local topic memory).
public struct TopicAliasBook: Codable, Sendable, Hashable {
    public var schemaVersion: Int
    public var aliases: [TopicQueryAlias]

    /// Oldest, least used aliases are dropped above this size.
    public static let maxAliases = 500

    public init(schemaVersion: Int = 1, aliases: [TopicQueryAlias] = []) {
        self.schemaVersion = schemaVersion
        self.aliases = aliases
    }

    enum CodingKeys: String, CodingKey {
        case schemaVersion, aliases
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        schemaVersion = c.lenientInt(.schemaVersion, default: 1)
        aliases = c.lossyArray(TopicQueryAlias.self, forKey: .aliases)
    }

    /// The alias for a query (compared by `TopicSearch.queryKey`).
    public func alias(for query: String) -> TopicQueryAlias? {
        let key = TopicSearch.queryKey(query)
        guard !key.isEmpty else { return nil }
        return aliases.first { $0.query == key }
    }

    /// Remembers that `query` means `topicID` (and optionally a category). Returns `false` when
    /// nothing was stored (queries shorter than 3 characters are ignored).
    @discardableResult
    public mutating func record(query: String, topicID: String, categoryID: String? = nil, now: Timestamp) -> Bool {
        let key = TopicSearch.queryKey(query)
        guard key.count >= 3, !topicID.isEmpty else { return false }
        if let index = aliases.firstIndex(where: { $0.query == key }) {
            var alias = aliases[index]
            if alias.topicID != topicID { alias.hits = 0 }
            alias.topicID = topicID
            alias.categoryID = categoryID
            alias.hits += 1
            alias.updatedAt = now
            aliases[index] = alias
            return true
        }
        aliases.append(TopicQueryAlias(query: key, topicID: topicID, categoryID: categoryID, updatedAt: now))
        trim()
        return true
    }

    /// Forgets a query („To nie ten temat”).
    @discardableResult
    public mutating func remove(query: String) -> Bool {
        let key = TopicSearch.queryKey(query)
        let before = aliases.count
        aliases.removeAll { $0.query == key }
        return aliases.count != before
    }

    /// Forgets every query pointing at a topic (e.g. a deleted generated topic).
    public mutating func removeTopic(_ topicID: String) {
        aliases.removeAll { $0.topicID == topicID }
    }

    private mutating func trim() {
        guard aliases.count > Self.maxAliases else { return }
        let sorted = aliases.sorted { (left: TopicQueryAlias, right: TopicQueryAlias) -> Bool in
            if left.hits != right.hits { return left.hits > right.hits }
            return left.updatedAt > right.updatedAt
        }
        aliases = Array(sorted.prefix(Self.maxAliases))
    }
}

/// A topic generated by AI and kept in the local topic memory (Application Support).
/// `topic` has the `TopicFile` format of CONTENT-SCHEMA §1; entries that are still drafts
/// (no details yet, see `TopicGeneration.isDraft`) have empty `examples`.
public struct GeneratedTopicRecord: Codable, Sendable, Hashable, Identifiable {
    public var schemaVersion: Int
    public var topic: TopicFile
    /// The query the topic was generated for.
    public var query: String
    /// AI provider id (`gemini`, `appleOnDevice`).
    public var provider: String
    public var createdAt: Timestamp
    public var updatedAt: Timestamp

    public init(schemaVersion: Int = 1, topic: TopicFile, query: String, provider: String, createdAt: Timestamp, updatedAt: Timestamp) {
        self.schemaVersion = schemaVersion
        self.topic = topic
        self.query = query
        self.provider = provider
        self.createdAt = createdAt
        self.updatedAt = updatedAt
    }

    public var id: String { topic.id }

    enum CodingKeys: String, CodingKey {
        case schemaVersion, topic, query, provider, createdAt, updatedAt
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        schemaVersion = c.lenientInt(.schemaVersion, default: 1)
        topic = try c.decode(TopicFile.self, forKey: .topic)
        query = c.lenientString(.query)
        provider = c.lenientString(.provider)
        createdAt = c.lenientDouble(.createdAt)
        updatedAt = c.lenientDouble(.updatedAt)
    }

    /// Entries with full details (usable for learning and quick-add).
    public var completeEntries: [TopicEntry] {
        topic.allEntries.filter { !TopicGeneration.isDraft($0) }
    }

    /// Dictionary-index records of the complete entries (for quick-add search).
    public var dictionaryEntries: [DictionaryIndex.Entry] {
        completeEntries.map { (entry: TopicEntry) -> DictionaryIndex.Entry in
            DictionaryIndex.Entry(
                term: entry.term,
                translation: entry.translation,
                level: entry.level,
                frequency: entry.frequency?.rawValue ?? "",
                reference: ContentReference(file: topic.id, entryID: entry.id).rawValue
            )
        }
    }
}
