import Foundation

// MARK: - Search documents

/// Lightweight view of a topic used by the topic search: names, aliases, categories with scenes
/// and the searchable text of entries (term, translation, `contextPl`). Decoded straight from
/// `topics/<id>.json` (examples and other heavy fields are skipped) or built from a `TopicFile`.
public struct TopicSearchDocument: Sendable, Hashable, Identifiable {
    public struct Entry: Sendable, Hashable {
        public var id: String
        public var term: String
        public var translation: String
        public var contextPl: String

        public init(id: String, term: String, translation: String, contextPl: String = "") {
            self.id = id
            self.term = term
            self.translation = translation
            self.contextPl = contextPl
        }
    }

    public struct Category: Sendable, Hashable, Identifiable {
        public var id: String
        public var namePl: String
        public var scenePl: String
        public var entries: [Entry]

        public init(id: String, namePl: String, scenePl: String = "", entries: [Entry] = []) {
            self.id = id
            self.namePl = namePl
            self.scenePl = scenePl
            self.entries = entries
        }
    }

    public var id: String
    public var namePl: String
    public var nameEn: String
    public var group: String
    public var symbol: String
    public var summaryPl: String
    public var aliases: [String]
    public var categories: [Category]
    /// `true` for topics generated by AI and kept in the local topic memory.
    public var isGenerated: Bool

    public init(
        id: String,
        namePl: String,
        nameEn: String = "",
        group: String = "",
        symbol: String = "",
        summaryPl: String = "",
        aliases: [String] = [],
        categories: [Category] = [],
        isGenerated: Bool = false
    ) {
        self.id = id
        self.namePl = namePl
        self.nameEn = nameEn
        self.group = group
        self.symbol = symbol
        self.summaryPl = summaryPl
        self.aliases = aliases
        self.categories = categories
        self.isGenerated = isGenerated
    }

    /// Search view of a full topic file.
    public init(topic: TopicFile, isGenerated: Bool = false) {
        self.init(
            id: topic.id,
            namePl: topic.namePl,
            nameEn: topic.nameEn,
            group: topic.group,
            symbol: topic.symbol,
            summaryPl: topic.summaryPl,
            aliases: topic.aliases,
            categories: topic.categories.map { (category: TopicCategory) -> Category in
                Category(
                    id: category.id,
                    namePl: category.namePl,
                    scenePl: category.scenePl,
                    entries: category.entries.map { (entry: TopicEntry) -> Entry in
                        Entry(id: entry.id, term: entry.term, translation: entry.translation, contextPl: entry.contextPl)
                    }
                )
            },
            isGenerated: isGenerated
        )
    }

    /// Number of entries.
    public var entryCount: Int {
        categories.reduce(0) { $0 + $1.entries.count }
    }
}

extension TopicSearchDocument.Entry: Decodable {
    enum CodingKeys: String, CodingKey {
        case id, term, translation, contextPl
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        term = try c.decode(String.self, forKey: .term)
        translation = c.lenientString(.translation)
        contextPl = c.lenientString(.contextPl)
    }
}

extension TopicSearchDocument.Category: Decodable {
    enum CodingKeys: String, CodingKey {
        case id, namePl, scenePl, entries
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        namePl = c.lenientString(.namePl)
        scenePl = c.lenientString(.scenePl)
        entries = c.lossyArray(TopicSearchDocument.Entry.self, forKey: .entries)
    }
}

extension TopicSearchDocument: Decodable {
    enum CodingKeys: String, CodingKey {
        case id, namePl, nameEn, group, symbol, summaryPl, aliases, categories
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        namePl = c.lenientString(.namePl)
        nameEn = c.lenientString(.nameEn)
        group = c.lenientString(.group)
        symbol = c.lenientString(.symbol)
        summaryPl = c.lenientString(.summaryPl)
        aliases = c.lenientStrings(.aliases)
        categories = c.lossyArray(TopicSearchDocument.Category.self, forKey: .categories)
        isGenerated = false
    }
}

extension ContentDecoder {
    /// Decodes only the searchable part of `topics/<id>.json` (much lighter than `topicFile`).
    public static func topicSearchDocument(from data: Data) throws -> TopicSearchDocument {
        try decode(TopicSearchDocument.self, from: data, file: "topics")
    }
}

// MARK: - Matches and results

/// How sure the search is that a topic answers the query.
public enum TopicMatchConfidence: Int, Sendable, Hashable, Comparable, CaseIterable {
    case low = 1
    case medium = 2
    case high = 3

    public static func < (lhs: TopicMatchConfidence, rhs: TopicMatchConfidence) -> Bool {
        lhs.rawValue < rhs.rawValue
    }

    /// Good enough to show the topic as the answer (no AI generation needed).
    public var isGood: Bool { self >= .medium }
}

/// What explained the match best.
public enum TopicMatchReason: String, Sendable, Hashable {
    /// The same query was answered by this topic before (local query memory).
    case savedQuery
    /// The topic name or one of its aliases.
    case name
    /// A category name of the topic.
    case category
    /// Only scenes, summaries or entries of the topic.
    case content
}

/// A category of a topic that matches the query more than the others (e.g. „Zamawianie” for
/// „zamawianie w restauracji”).
public struct TopicFocus: Sendable, Hashable {
    public var categoryID: String
    public var score: Double

    public init(categoryID: String, score: Double) {
        self.categoryID = categoryID
        self.score = score
    }
}

/// One ranked topic.
public struct TopicMatch: Sendable, Hashable, Identifiable {
    public var topicID: String
    /// Relevance (≈ 0.4…1.6; higher is better). Only comparable within one query.
    public var score: Double
    public var confidence: TopicMatchConfidence
    /// Best matching categories (at most 2), most relevant first.
    public var focus: [TopicFocus]
    /// The query and a topic name / alias are the same (after normalisation and stemming).
    public var isExactName: Bool
    public var reason: TopicMatchReason
    public var isGenerated: Bool

    public init(topicID: String, score: Double, confidence: TopicMatchConfidence, focus: [TopicFocus] = [], isExactName: Bool = false, reason: TopicMatchReason, isGenerated: Bool = false) {
        self.topicID = topicID
        self.score = score
        self.confidence = confidence
        self.focus = focus
        self.isExactName = isExactName
        self.reason = reason
        self.isGenerated = isGenerated
    }

    public var id: String { topicID }

    /// Ids of the focus categories.
    public var focusCategoryIDs: [String] { focus.map { $0.categoryID } }
}

/// A ranked topic with what the UI needs to show it as a suggestion.
public struct TopicSuggestion: Sendable, Hashable, Identifiable {
    public var match: TopicMatch
    public var namePl: String
    public var nameEn: String
    public var symbol: String
    public var summaryPl: String
    public var entryCount: Int
    /// Names of the focus categories (for „Lotnisko · Odprawa”).
    public var focusNames: [String]

    public init(match: TopicMatch, namePl: String, nameEn: String = "", symbol: String = "", summaryPl: String = "", entryCount: Int = 0, focusNames: [String] = []) {
        self.match = match
        self.namePl = namePl
        self.nameEn = nameEn
        self.symbol = symbol
        self.summaryPl = summaryPl
        self.entryCount = entryCount
        self.focusNames = focusNames
    }

    public var id: String { match.topicID }
}

/// A section of the topic search result.
public struct TopicResultSection: Sendable, Hashable, Identifiable {
    public enum Kind: String, Sendable, Hashable {
        /// The best matching category of the best topic.
        case focus
        /// The rest of the best topic (one section per category).
        case topic
        /// Matching categories of other related topics.
        case related
    }

    public var kind: Kind
    public var topicID: String
    public var topicName: String
    public var categoryID: String
    public var title: String
    public var subtitle: String
    /// Entries ordered by usefulness: spoken frequency first, then CEFR level.
    public var entries: [TopicEntry]

    public init(kind: Kind, topicID: String, topicName: String, categoryID: String, title: String, subtitle: String = "", entries: [TopicEntry]) {
        self.kind = kind
        self.topicID = topicID
        self.topicName = topicName
        self.categoryID = categoryID
        self.title = title
        self.subtitle = subtitle
        self.entries = entries
    }

    public var id: String { "\(kind.rawValue)|\(topicID)|\(categoryID)" }

    /// Content reference of an entry of this section (`<topic>/<entry id>`).
    public func reference(of entry: TopicEntry) -> String {
        ContentReference(file: topicID, entryID: entry.id).rawValue
    }
}

// MARK: - Catalog

/// Precomputed search structures for all topics (built-in + generated) and remembered queries.
/// Build once off the main thread; `TopicSearch.rank` is then fast (a few ms for ~150 topics).
public struct TopicSearchCatalog: Sendable {
    public let documents: [TopicSearchDocument]
    public let savedQueries: [TopicQueryAlias]
    let indexed: [TopicSearchIndexedTopic]
    let savedByKey: [String: TopicQueryAlias]
    let positions: [String: Int]

    public init(documents: [TopicSearchDocument], savedQueries: [TopicQueryAlias] = []) {
        // Later documents with the same id win (a generated topic never shadows a built-in one:
        // generated ids are always prefixed — see `TopicGeneration.idPrefix`).
        var unique: [TopicSearchDocument] = []
        var positions: [String: Int] = [:]
        for document in documents {
            if let existing = positions[document.id] {
                unique[existing] = document
            } else {
                positions[document.id] = unique.count
                unique.append(document)
            }
        }
        var savedByTopic: [String: [String]] = [:]
        var savedByKey: [String: TopicQueryAlias] = [:]
        for alias in savedQueries where positions[alias.topicID] != nil {
            savedByTopic[alias.topicID, default: []].append(alias.query)
            savedByKey[alias.query] = alias
        }
        self.documents = unique
        self.savedQueries = savedQueries
        self.positions = positions
        self.savedByKey = savedByKey
        self.indexed = unique.map { (document: TopicSearchDocument) -> TopicSearchIndexedTopic in
            TopicSearchIndexedTopic(document: document, savedQueries: savedByTopic[document.id] ?? [])
        }
    }

    /// Number of topics.
    public var count: Int { documents.count }

    public func document(id: String) -> TopicSearchDocument? {
        guard let position = positions[id] else { return nil }
        return documents[safe: position]
    }

    /// Display data for ranked topics (unknown ids are skipped).
    public func suggestions(for matches: [TopicMatch]) -> [TopicSuggestion] {
        matches.compactMap { (match: TopicMatch) -> TopicSuggestion? in
            guard let document = document(id: match.topicID) else { return nil }
            let names = match.focus.compactMap { focus in
                document.categories.first(where: { $0.id == focus.categoryID })?.namePl
            }
            return TopicSuggestion(
                match: match,
                namePl: document.namePl,
                nameEn: document.nameEn,
                symbol: document.symbol,
                summaryPl: document.summaryPl,
                entryCount: document.entryCount,
                focusNames: names
            )
        }
    }
}

/// Token = folded ASCII bytes (`a-z`, `0-9`).
typealias TopicToken = [UInt8]

/// Unique tokens bucketed by first byte (stem, prefix and typo matches share the first letter).
struct TopicTokenBag: Sendable {
    let tokens: [TopicToken]
    let buckets: [UInt8: [TopicToken]]

    init(_ input: [TopicToken]) {
        var seen = Set<TopicToken>()
        var unique: [TopicToken] = []
        var buckets: [UInt8: [TopicToken]] = [:]
        for token in input where !token.isEmpty && seen.insert(token).inserted {
            unique.append(token)
            if let first = token.first {
                buckets[first, default: []].append(token)
            }
        }
        self.tokens = unique
        self.buckets = buckets
    }

    var isEmpty: Bool { tokens.isEmpty }

    /// Best similarity of `query` to any token of the bag.
    func best(_ query: TopicToken, fuzzy: Bool) -> Double {
        guard let first = query.first, let bucket = buckets[first] else { return 0 }
        var result = 0.0
        for token in bucket {
            let value = TopicSearch.similarity(query, token, fuzzy: fuzzy)
            if value > result {
                result = value
                if result >= 1 { break }
            }
        }
        return result
    }
}

struct TopicSearchIndexedCategory: Sendable {
    let id: String
    let nameTokens: [TopicToken]
    let name: TopicTokenBag
    let scene: TopicTokenBag
    let entries: TopicTokenBag
}

struct TopicSearchIndexedTopic: Sendable {
    let variants: [[TopicToken]]
    let names: TopicTokenBag
    let mainNames: TopicTokenBag
    let summary: TopicTokenBag
    let group: TopicTokenBag
    let categories: [TopicSearchIndexedCategory]

    init(document: TopicSearchDocument, savedQueries: [String]) {
        let rawVariants = [document.namePl, document.nameEn] + document.aliases + savedQueries
        let variants = rawVariants
            .map { TopicSearch.keywordTokens($0) }
            .filter { !$0.isEmpty }
        self.variants = variants
        names = TopicTokenBag(variants.flatMap { $0 })
        mainNames = TopicTokenBag(TopicSearch.keywordTokens(document.namePl) + TopicSearch.keywordTokens(document.nameEn))
        summary = TopicTokenBag(TopicSearch.tokens(document.summaryPl))
        group = TopicTokenBag(TopicSearch.tokens(TopicGeneration.groupName(document.group)))
        categories = document.categories.map { (category: TopicSearchDocument.Category) -> TopicSearchIndexedCategory in
            let nameTokens = TopicSearch.keywordTokens(category.namePl)
            var entryTokens: [TopicToken] = []
            for entry in category.entries {
                entryTokens.append(contentsOf: TopicSearch.tokens(entry.term))
                entryTokens.append(contentsOf: TopicSearch.tokens(entry.translation))
                entryTokens.append(contentsOf: TopicSearch.tokens(entry.contextPl))
            }
            return TopicSearchIndexedCategory(
                id: category.id,
                nameTokens: nameTokens,
                name: TopicTokenBag(nameTokens),
                scene: TopicTokenBag(TopicSearch.tokens(category.scenePl)),
                entries: TopicTokenBag(entryTokens)
            )
        }
    }
}

// MARK: - Search

/// Finding vocabulary topics for a free-text description of a situation („zamawianie w restauracji”,
/// „na lotnisku”, „job interview”). Polish-aware: diacritics folded, prepositions ignored, simple
/// stemming by a shared prefix with an inflectional ending („lotnisku” = „lotnisko”), typo tolerance.
///
/// Scoring (per query keyword, best of): topic name / alias / remembered query (1.0), category name
/// (0.9), scene or summary (0.6), group (0.5), entry term / translation / context (0.5); averaged over
/// keywords, plus bonuses for a whole alias equal to the query (+0.3) or contained in it (+0.2),
/// a whole category name (+0.15) and the main topic name (≤ +0.1). A topic is „anchored” when a
/// keyword hits its name, an alias or a category name — unanchored topics are at most `low`.
public enum TopicSearch {
    /// Minimum score of a returned match.
    public static let minimumScore = 0.4
    static let highScore = 0.8
    static let mediumScore = 0.6

    // MARK: Text

    private static let stopwordList = [
        "w", "we", "na", "o", "do", "przy", "z", "ze", "u", "i", "a", "oraz", "lub", "albo", "dla", "po", "od",
        "za", "pod", "nad", "przed", "sie", "jak", "co", "to", "ten", "ta", "te", "jest", "czy", "mnie", "moj",
        "moja", "moje", "przez", "bez", "mi",
        "the", "an", "at", "in", "on", "of", "for", "and", "or", "with", "my", "your", "about", "from", "by",
        "into", "how", "what", "is", "are"
    ]
    private static let stopwords: Set<TopicToken> = Set(stopwordList.map { Array($0.utf8) })

    /// Inflectional endings (Polish cases, English -s/-ing/-ed…) allowed after a shared stem.
    private static let endingList = [
        "", "a", "e", "i", "o", "u", "y", "ie", "ia", "iu", "ii", "ach", "ami", "om", "ow", "owi", "owie",
        "ej", "ego", "emu", "ym", "ymi", "ich", "imi", "em", "ek", "ku", "ka", "ki", "ko", "ce", "ta", "cie",
        "dzie", "rze", "s", "es", "ed", "ing", "er", "ers", "ies", "ly"
    ]
    private static let endings: Set<TopicToken> = Set(endingList.map { Array($0.utf8) })

    /// Lowercase, no diacritics (`ł`→`l`), only `a-z0-9`, single spaces.
    public static func normalize(_ text: String) -> String {
        tokenize(text, minimumLength: 1).map { String(decoding: $0, as: UTF8.self) }.joined(separator: " ")
    }

    /// Search keywords of a text (stopwords removed unless the text has nothing else).
    public static func keywords(_ text: String) -> [String] {
        keywordTokens(text).map { String(decoding: $0, as: UTF8.self) }
    }

    /// Key under which a query is remembered (keywords joined with spaces).
    public static func queryKey(_ text: String) -> String {
        keywords(text).joined(separator: " ")
    }

    static func tokens(_ text: String) -> [TopicToken] {
        tokenize(text, minimumLength: 2)
    }

    static func keywordTokens(_ text: String) -> [TopicToken] {
        let all = tokens(text)
        let filtered = all.filter { !stopwords.contains($0) }
        return filtered.isEmpty ? all : filtered
    }

    private static func tokenize(_ text: String, minimumLength: Int) -> [TopicToken] {
        let folded = TextScanning.foldPolish(text)
        var result: [TopicToken] = []
        var current: TopicToken = []
        for scalar in folded.unicodeScalars {
            let value = scalar.value
            if (97...122).contains(value) || (48...57).contains(value) {
                current.append(UInt8(value))
            } else if !current.isEmpty {
                if current.count >= minimumLength { result.append(current) }
                current = []
            }
        }
        if current.count >= minimumLength && !current.isEmpty { result.append(current) }
        return result
    }

    // MARK: Similarity

    /// Similarity of a query token to a candidate token:
    /// 1 equal · 0.85 same stem + inflectional endings · 0.7 typed prefix (≥ 4 letters) ·
    /// 0.75 / 0.7 one / two typos (only when `fuzzy`; two typos for words of ≥ 7 letters) · 0.
    static func similarity(_ query: TopicToken, _ candidate: TopicToken, fuzzy: Bool) -> Double {
        if query == candidate { return 1 }
        guard let q0 = query.first, let c0 = candidate.first, q0 == c0 else { return 0 }
        let shorter = Swift.min(query.count, candidate.count)
        var prefix = 0
        while prefix < shorter && query[prefix] == candidate[prefix] {
            prefix += 1
        }
        if shorter >= 4 && prefix >= 4 {
            let queryEnding = Array(query[prefix...])
            let candidateEnding = Array(candidate[prefix...])
            if endings.contains(queryEnding) && endings.contains(candidateEnding) { return 0.85 }
        }
        if query.count >= 4 && prefix == query.count { return 0.7 }
        if fuzzy && shorter >= 4 {
            let allowed = shorter >= 7 ? 2 : 1
            if abs(query.count - candidate.count) <= allowed + 1,
               let distance = osaDistance(query, candidate, limit: allowed) {
                return distance <= 1 ? 0.75 : 0.7
            }
        }
        return 0
    }

    /// Optimal string alignment distance (Levenshtein + adjacent transposition); `nil` above `limit`.
    static func osaDistance(_ a: TopicToken, _ b: TopicToken, limit: Int) -> Int? {
        let n = a.count
        let m = b.count
        if n == 0 { return m <= limit ? m : nil }
        if m == 0 { return n <= limit ? n : nil }
        var twoBack = [Int](repeating: 0, count: m + 1)
        var previous = Array(0...m)
        var current = [Int](repeating: 0, count: m + 1)
        for i in 1...n {
            current[0] = i
            var rowMinimum = current[0]
            for j in 1...m {
                let cost = a[i - 1] == b[j - 1] ? 0 : 1
                var value = Swift.min(previous[j] + 1, current[j - 1] + 1, previous[j - 1] + cost)
                if i > 1 && j > 1 && a[i - 1] == b[j - 2] && a[i - 2] == b[j - 1] {
                    value = Swift.min(value, twoBack[j - 2] + 1)
                }
                current[j] = value
                if value < rowMinimum { rowMinimum = value }
            }
            if rowMinimum > limit { return nil }
            twoBack = previous
            previous = current
        }
        let distance = previous[m]
        return distance <= limit ? distance : nil
    }

    private static func coverage(_ from: [TopicToken], _ to: TopicTokenBag, fuzzy: Bool) -> Double {
        guard !from.isEmpty else { return 0 }
        var sum = 0.0
        for token in from {
            sum += to.best(token, fuzzy: fuzzy)
        }
        return sum / Double(from.count)
    }

    // MARK: Ranking

    /// Topics for a query, best first. Matches below `minimumScore` are dropped.
    public static func rank(_ query: String, in catalog: TopicSearchCatalog, limit: Int = 8) -> [TopicMatch] {
        let keywords = keywordTokens(query)
        guard !keywords.isEmpty, limit > 0 else { return [] }
        let queryBag = TopicTokenBag(keywords)
        let saved = catalog.savedByKey[queryKey(query)]
        var matches: [TopicMatch] = []
        for (position, topic) in catalog.indexed.enumerated() {
            guard let document = catalog.documents[safe: position] else { continue }
            let savedHere = saved?.topicID == document.id ? saved : nil
            guard var match = score(keywords, queryBag: queryBag, topic: topic, document: document) ?? savedFallback(savedHere, document: document) else {
                continue
            }
            if let savedHere {
                match.score = Swift.max(match.score, 1.5)
                match.confidence = .high
                match.reason = .savedQuery
                if let categoryID = savedHere.categoryID,
                   document.categories.contains(where: { $0.id == categoryID }) {
                    match.focus.removeAll { $0.categoryID == categoryID }
                    match.focus.insert(TopicFocus(categoryID: categoryID, score: 1), at: 0)
                    match.focus = Array(match.focus.prefix(2))
                }
            }
            matches.append(match)
        }
        let sorted = matches.sorted { (left: TopicMatch, right: TopicMatch) -> Bool in
            if left.score != right.score { return left.score > right.score }
            if left.isGenerated != right.isGenerated { return !left.isGenerated }
            return left.topicID < right.topicID
        }
        return Array(sorted.prefix(limit))
    }

    /// The best match when it is good enough to answer the query without AI.
    public static func bestMatch(_ query: String, in catalog: TopicSearchCatalog) -> TopicMatch? {
        guard let first = rank(query, in: catalog, limit: 1).first, first.confidence.isGood else { return nil }
        return first
    }

    private static func savedFallback(_ saved: TopicQueryAlias?, document: TopicSearchDocument) -> TopicMatch? {
        guard saved != nil else { return nil }
        return TopicMatch(topicID: document.id, score: 1.5, confidence: .high, reason: .savedQuery, isGenerated: document.isGenerated)
    }

    private static func score(_ keywords: [TopicToken], queryBag: TopicTokenBag, topic: TopicSearchIndexedTopic, document: TopicSearchDocument) -> TopicMatch? {
        var sum = 0.0
        var anchored = false
        var hitName = false
        var hitCategory = false
        var mainScores: [Double] = []
        for keyword in keywords {
            let nameScore = topic.names.best(keyword, fuzzy: true)
            mainScores.append(topic.mainNames.best(keyword, fuzzy: true))
            var best = nameScore
            if nameScore >= 0.7 {
                anchored = true
                hitName = true
            }
            for category in topic.categories {
                let categoryName = category.name.best(keyword, fuzzy: true)
                if categoryName >= 0.7 {
                    anchored = true
                    hitCategory = true
                }
                best = Swift.max(best, categoryName * 0.9, category.scene.best(keyword, fuzzy: false) * 0.6, category.entries.best(keyword, fuzzy: false) * 0.5)
            }
            best = Swift.max(best, topic.summary.best(keyword, fuzzy: false) * 0.6, topic.group.best(keyword, fuzzy: false) * 0.5)
            sum += best
        }
        let count = Double(keywords.count)
        var total = sum / count
        var exact = false
        var contained = false
        for variant in topic.variants {
            let variantBag = TopicTokenBag(variant)
            let forward = coverage(keywords, variantBag, fuzzy: true)
            let backward = coverage(variant, queryBag, fuzzy: true)
            if forward >= 0.8 && backward >= 0.8 {
                exact = true
                break
            }
            if backward >= 0.8 { contained = true }
        }
        total += exact ? 0.3 : (contained ? 0.2 : 0)
        let wholeCategory = topic.categories.contains { (category: TopicSearchIndexedCategory) -> Bool in
            coverage(keywords, category.name, fuzzy: true) >= 0.8 && coverage(category.nameTokens, queryBag, fuzzy: true) >= 0.8
        }
        if wholeCategory { total += 0.15 }
        total += 0.1 * (mainScores.reduce(0, +) / count)
        guard total >= minimumScore else { return nil }
        let confidence: TopicMatchConfidence
        if !anchored {
            confidence = .low
        } else if total >= highScore {
            confidence = .high
        } else if total >= mediumScore {
            confidence = .medium
        } else {
            confidence = .low
        }
        let reason: TopicMatchReason = hitName ? .name : (hitCategory ? .category : .content)
        let focus = focusCategories(keywords, queryBag: queryBag, mainScores: mainScores, topic: topic)
        return TopicMatch(
            topicID: document.id,
            score: (total * 1000).rounded() / 1000,
            confidence: confidence,
            focus: focus,
            isExactName: exact,
            reason: reason,
            isGenerated: document.isGenerated
        )
    }

    /// Categories that explain the query better than the rest of the topic. Keywords already
    /// explained by the main topic name („restauracji” in „zamawianie w restauracji”) are ignored;
    /// when nothing is left, only category names count („odprawa” → „Odprawa”).
    private static func focusCategories(_ keywords: [TopicToken], queryBag: TopicTokenBag, mainScores: [Double], topic: TopicSearchIndexedTopic) -> [TopicFocus] {
        var extra: [TopicToken] = []
        for (index, keyword) in keywords.enumerated() where (mainScores[safe: index] ?? 0) < 0.8 {
            extra.append(keyword)
        }
        let nameOnly = extra.isEmpty
        let basis = nameOnly ? keywords : extra
        let count = Double(basis.count)
        var scored: [TopicFocus] = []
        for category in topic.categories {
            var content = 0.0
            var names = 0.0
            for keyword in basis {
                let name = category.name.best(keyword, fuzzy: true)
                names += name
                content += Swift.max(name, category.scene.best(keyword, fuzzy: false) * 0.7, category.entries.best(keyword, fuzzy: false) * 0.6)
            }
            content /= count
            names /= count
            let backward = coverage(category.nameTokens, queryBag, fuzzy: true)
            let blended = 0.7 * names + 0.3 * backward
            let value: Double
            if nameOnly {
                value = names > 0 ? blended : 0
            } else {
                value = names > 0 ? Swift.max(content, blended) : content
            }
            scored.append(TopicFocus(categoryID: category.id, score: (value * 1000).rounded() / 1000))
        }
        let threshold = nameOnly ? 0.5 : 0.55
        let candidates = scored
            .filter { $0.score >= threshold }
            .sorted { $0.score > $1.score }
        guard let best = candidates.first else { return [] }
        // A „match” in most categories is not a focus (e.g. the topic name repeated in every scene).
        guard candidates.count <= Swift.max(2, topic.categories.count / 2) else { return [] }
        return Array(candidates.filter { $0.score >= best.score - 0.15 }.prefix(2))
    }

    // MARK: Results

    /// Entries ordered by usefulness: spoken frequency (very common first), then CEFR (A1 first),
    /// then the original order (authors list the core of the situation first).
    public static func usefulnessOrder(_ entries: [TopicEntry]) -> [TopicEntry] {
        entries.stableSorted { (left: TopicEntry, right: TopicEntry) -> Bool in
            let leftFrequency = left.frequency?.rank ?? 4
            let rightFrequency = right.frequency?.rank ?? 4
            if leftFrequency != rightFrequency { return leftFrequency < rightFrequency }
            let leftLevel = CEFR.index(of: left.level) ?? 6
            let rightLevel = CEFR.index(of: right.level) ?? 6
            return leftLevel < rightLevel
        }
    }

    /// Related topics worth showing below the best one: confident, close in score and with a
    /// clearly matching category (at most `limit`).
    public static func relatedMatches(_ matches: [TopicMatch], primary: TopicMatch, limit: Int = 2) -> [TopicMatch] {
        let threshold = primary.score * 0.6
        let related = matches.filter { (match: TopicMatch) -> Bool in
            match.topicID != primary.topicID
                && match.confidence.isGood
                && match.score >= threshold
                && (match.focus.first?.score ?? 0) >= 0.75
        }
        return Array(related.prefix(limit))
    }

    /// Result sections: the focus categories of the best topic, then the rest of that topic
    /// (category by category, in the topic's order), then the focus categories of related topics.
    /// Inside every section entries follow `usefulnessOrder`. Duplicates (same term and
    /// translation) are shown once — in the first section.
    public static func sections(
        primary: TopicMatch,
        topic: TopicFile,
        related: [(match: TopicMatch, topic: TopicFile)] = [],
        relatedEntryLimit: Int = 12
    ) -> [TopicResultSection] {
        var seen = Set<String>()
        var result: [TopicResultSection] = []

        func unique(_ entries: [TopicEntry]) -> [TopicEntry] {
            entries.filter { seen.insert(duplicateKey($0)).inserted }
        }

        let focusIDs = primary.focusCategoryIDs
        for categoryID in focusIDs {
            guard let category = topic.categories.first(where: { $0.id == categoryID }) else { continue }
            let entries = unique(usefulnessOrder(category.entries))
            guard !entries.isEmpty else { continue }
            result.append(TopicResultSection(kind: .focus, topicID: topic.id, topicName: topic.namePl, categoryID: category.id,
                                             title: category.namePl, subtitle: category.scenePl, entries: entries))
        }
        for category in topic.categories where !focusIDs.contains(category.id) {
            let entries = unique(usefulnessOrder(category.entries))
            guard !entries.isEmpty else { continue }
            result.append(TopicResultSection(kind: .topic, topicID: topic.id, topicName: topic.namePl, categoryID: category.id,
                                             title: category.namePl, subtitle: category.scenePl, entries: entries))
        }
        for item in related where item.topic.id != topic.id {
            for categoryID in item.match.focusCategoryIDs {
                guard let category = item.topic.categories.first(where: { $0.id == categoryID }) else { continue }
                let entries = Array(unique(usefulnessOrder(category.entries)).prefix(relatedEntryLimit))
                guard !entries.isEmpty else { continue }
                result.append(TopicResultSection(kind: .related, topicID: item.topic.id, topicName: item.topic.namePl,
                                                 categoryID: category.id, title: "\(item.topic.namePl): \(category.namePl)",
                                                 subtitle: category.scenePl, entries: entries))
            }
        }
        return result
    }

    /// The same term with the same translation (also without a dialect label — the key of
    /// `OwnedVocabulary` and `SenseGrouping`, FEEDBACK-8 M3) is shown once.
    static func duplicateKey(_ entry: TopicEntry) -> String {
        OwnedVocabulary.termKey(entry.term) + "|" + OwnedVocabulary.translationKey(entry.translation)
    }
}
